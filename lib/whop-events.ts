import "server-only";
import { z } from "zod";
import { getWhop, whopSandbox } from "./whop";
import { getSession } from "./supabase";
import { handleWhopPaymentSuccess } from "./payment-success";
import { usdCents } from "./whop-validation";
import { verifyLocalTestAmount } from "./test-payment-tax";
const eventSchema = z
  .object({
    type: z.string(),
    data: z.unknown(),
  })
  .passthrough();
export async function processWhopEvent(raw: unknown) {
  const event = eventSchema.parse(raw);
  if (event.type !== "payment.succeeded")
    return { received: true, ignored: true };
  const data = z
    .object({ id: z.string().startsWith("pay_") })
    .parse(event.data);
  const payment = await getWhop().payments.retrieve({ id: data.id });
  if (
    payment.status !== "paid" ||
    !payment.paid_at ||
    payment.account_id !== process.env.WHOP_COMPANY_ID
  )
    throw new Error("The payment is not confirmed for this company.");
  const reference = z.uuid().safeParse(payment.metadata?.checkout_session_id);
  if (
    !reference.success ||
    !["sale", "deposit"].includes(String(payment.metadata?.checkout_type))
  )
    return {
      received: true,
      ignored: true,
      reason: "Payment was not generated by Payment Desk.",
    };
  const sessionId = reference.data;
  const session = await getSession(sessionId);
  if (!session) throw new Error("Checkout session has not been saved yet.");
  if (
    session.mode !== (whopSandbox() ? "sandbox" : "live") ||
    session.whop_checkout_id !== payment.checkout_configuration_id
  )
    throw new Error("Payment does not match its checkout session.");
  if (
    payment.currency !== "usd" ||
    !payment.total ||
    payment.total.currency !== "usd"
  )
    throw new Error("Only verified USD payments are supported.");
  const localTest = !process.env.VERCEL && process.env.PAYMENT_DESK_LOCAL_TEST === "true";
  if (localTest && (payment.plan_id !== process.env.WHOP_LOCAL_TEST_PLAN_ID || session.amount_due_today !== 100))
    throw new Error("Local testing only accepts the configured $1 test plan.");
  const amount = localTest ? verifyLocalTestAmount(payment, session.amount_due_today) : usdCents(payment.total.amount);
  if (amount <= 0) throw new Error("No positive payment was collected.");
  return handleWhopPaymentSuccess(
    {
      checkout_session_id: session.id,
      whop_payment_id: payment.id,
      amount_collected: amount,
      paid_at: payment.paid_at,
    },
    { session },
  );
}
